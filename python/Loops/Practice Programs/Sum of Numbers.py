total = 0 

for i in range(1, 11):  
    total += i    # 0 += 1 =1 , 1+=2=3 , 3+=4=10 
print(total)


# for loop → Fixed number of times repeat karna ho.
# while loop → Condition ke basis par repeat karna ho.
# range() → Number sequence banata hai.
# break → Loop stop.
# continue → Current iteration skip.
# nested loop → Loop ke andar loop.
# pass → Empty block ke liye use hota hai.